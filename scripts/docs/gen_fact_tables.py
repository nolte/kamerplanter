"""Generate MkDocs fact-table snippets from backend code and seed data.

Standalone pre-build script, modelled on ``scripts/docs/gen_catalog.py``. It
reads the *authoritative* sources for three tables that used to be hand-kept in
the docs (and therefore drifted from the code — docs audit pattern M-3) and
writes deterministic Markdown table snippets into ``docs/_generated/``, one file
per table and locale (``.de.md`` / ``.en.md``).

Sources
-------
* ``CARE_STYLE_PRESETS`` and ``FAMILY_CARE_MAP`` in
  ``src/backend/app/domain/engines/care_reminder_engine.py`` — parsed via the
  Python AST (no import of the backend package, so the script runs in the plain
  docs toolchain without pydantic/app dependencies).
* ``src/backend/app/migrations/seed_data/starter_kits.yaml`` — parsed as YAML.

The numeric/enumerated *facts* (intervals, winter factors, active months,
watering method, auto style, difficulty, environment) come straight from those
sources, so they can never drift again. Purely editorial presentation data that
is not in the code — the human-readable style labels, the typical-plant
examples and the German/English family common names — lives in the
``*_META`` tables below (the doc-side equivalent of the frontend ``enums.*``
translations).

The generated files are ``.gitignored`` and must be regenerated before every
docs build. ``task docs:build`` / ``task docs:serve`` depend on
``task docs:fact-tables`` which runs this script.

The script fails loudly (``FactTableError``, non-zero exit) whenever a source
gains an entry that has no presentation metadata here, so a code change can
never silently drop a row or ship an untranslated one.
"""

