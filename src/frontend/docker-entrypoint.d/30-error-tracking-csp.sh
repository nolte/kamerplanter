#!/bin/sh
# Allow the error tracker's ingest origin in the CSP — but only when one is
# configured (#777, #3025 W-21).
#
# The shipped policy is `connect-src 'self'${kp_csp_connect_extra}`; the
# variable comes from a `map` in the nginx configuration that includes every
# `*.conf` in the runtime directory. This script writes exactly one such file,
# holding the one origin the configured DSN points at, and removes it when no
# usable DSN is configured, so a deployment without a tracker keeps the plain
# `connect-src 'self'` and a container restart never keeps a stale origin.
#
# Two callers, one validation:
#   * the image (Compose): nginx's entrypoint runs this from
#     /docker-entrypoint.d with the default runtime directory;
#   * the Helm chart: /docker-entrypoint.d and /etc/nginx/conf.d are read-only
#     or suppressed in the pod, so the init container (same image) runs this
#     script with KP_NGINX_RUNTIME_DIR pointing at an emptyDir that the nginx
#     container mounts at /etc/nginx/runtime.
#
# The DSN has the form https://<public-key>@<host>/<project-id>; only the scheme
# and host go into the policy. The key never reaches the header.
set -eu

RUNTIME_DIR="${KP_NGINX_RUNTIME_DIR:-/etc/nginx/runtime}"
OUT_FILE="${RUNTIME_DIR}/csp-connect-src.conf"

# Start from "no extra origin" on every run.
rm -f "$OUT_FILE"

DSN="${SENTRY_DSN:-}"
[ -n "$DSN" ] || exit 0

# scheme://[credentials@]host[/...]  ->  scheme://host
SCHEME=$(printf '%s' "$DSN" | sed -n 's|^\([a-zA-Z][a-zA-Z0-9+.-]*\)://.*|\1|p')
HOST=$(printf '%s' "$DSN" | sed -e 's|^[a-zA-Z][a-zA-Z0-9+.-]*://||' -e 's|^[^@/]*@||' -e 's|/.*$||')

# Validate before the value reaches a CSP directive. Whoever sets SENTRY_DSN
# already controls the deployment, so this is not a privilege boundary — but the
# value flows into a security header and into nginx configuration, and a DSN
# without a path (`https://host; script-src *`) would otherwise carry every
# character after the host straight into the policy. A malformed DSN must
# degrade to "tracking does not reach the server", never to "the page's CSP
# quietly grew a directive".
case "$SCHEME" in
    http | https) ;;
    *)
        echo "WARN  SENTRY_DSN scheme '${SCHEME}' is not http(s); CSP left unchanged." >&2
        echo "      Error events will be blocked by connect-src 'self'." >&2
        exit 0
        ;;
esac

# Host, optionally with a port. Deliberately no `;`, no space, no quote — the
# characters a CSP directive and an nginx string are delimited by.
# The port, when present, is digits only (`https://:` or `host:x` is no origin).
case "$HOST" in
    "" | *[!A-Za-z0-9.:-]* | :* | *: | *:*:* | *:*[!0-9]*)
        echo "WARN  SENTRY_DSN host '${HOST}' is not a bare host[:port]; CSP left unchanged." >&2
        echo "      Error events will be blocked by connect-src 'self'." >&2
        exit 0
        ;;
esac

ORIGIN="${SCHEME}://${HOST}"

if ! mkdir -p "$RUNTIME_DIR" 2>/dev/null || ! [ -w "$RUNTIME_DIR" ]; then
    echo "WARN  $RUNTIME_DIR is not writable; CSP left unchanged." >&2
    echo "      Error events will be blocked by connect-src 'self'." >&2
    exit 0
fi

# A `map` entry: the default value of $kp_csp_connect_extra. The leading space
# separates it from 'self' in the header.
printf '# Generated by 30-error-tracking-csp.sh at container start (#777).\ndefault " %s";\n' "$ORIGIN" >"$OUT_FILE"
echo "INFO  CSP connect-src extended with the error-tracking origin ${ORIGIN}." >&2
